fn memory(va: u64, len: usize) -> Option<Vec<u8>> {
    let from = usize::try_from(va.checked_sub(BASE)?).ok()?;
    BYTES.get(from..from.checked_add(len)?).map(<[u8]>::to_vec)
}

fn instructions() -> Vec<(u64, pcode_ir::Instruction)> {
    let mut decoder = Decoder::new(Architecture::X86_64);
    let mut out = Vec::new();
    let mut address = BASE;
    while address < CODE_END {
        let offset = (address - BASE) as usize;
        let inst = decoder.decode(&BYTES[offset..], address).unwrap();
        address += inst.len;
        out.push((address - inst.len, inst));
    }
    out
}

#[test]
fn image_relative_table_with_signed_byte_index_is_recovered() {
    let tables = rsleigh_decompile::jump_table::find(&instructions(), &memory);
    let table = tables
        .iter()
        .find(|t| t.jump == JUMP)
        .expect("no jump table recovered for the dispatch at 0x18006a520");
    // Cases -1..=5 in order; 6 onward is 0xcccccccc padding.
    assert_eq!(
        table.targets,
        [
            0x1_8006_a644, // -1: noreturn call
            0x1_8006_a572, // 0: return
            0x1_8006_a572, // 1: return
            0x1_8006_a522, // 2
            0x1_8006_a578, // 3
            0x1_8006_a572, // 4: return
            0x1_8006_a572, // 5: return
        ]
    );
}

#[test]
fn switch_chain_tests_case_values_from_minus_one() {
    let cfg = rsleigh_decompile::cfg::build_cfg_with_memory(&instructions(), &memory);
    assert!(
        !cfg.diagnostics.iter().any(|d| matches!(
            d.kind,
            DiagKind::UnrecoveredIndirectJump | DiagKind::UnresolvedBranchTarget
        ) && d.addr == Some(JUMP)),
        "dispatch left unresolved: {:?}",
        cfg.diagnostics
    );
    // `cfg::switch_chain` tests every case but the last against the index.
    let tested: Vec<i64> = cfg
        .blocks
        .iter()
        .flat_map(|b| &b.ops)
        .filter(|(at, _)| *at == JUMP)
        .filter_map(|(_, op)| match op {
            PcodeOp::IntEq { right, .. } if right.space == AddressSpaceId::Const => {
                Some(right.offset as i64)
            }
            _ => None,
        })
        .collect();
    assert_eq!(tested, [-1, 0, 1, 2, 3, 4]);
}

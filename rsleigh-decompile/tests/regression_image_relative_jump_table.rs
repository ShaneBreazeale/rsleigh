//! MSVC/clang-cl x86-64 switch whose table holds image-base-relative entries
//! and whose index is a signed byte with no bounds check:
//!
//! ```text
//! 18006a509  movsx rax, byte [rdx + 0x48]
//! 18006a50e  lea   r8, [0x180000000]          ; image base, not the table
//! 18006a515  mov   eax, [r8 + rax*4 + 0x6a650] ; zero-extending 32-bit load
//! 18006a51d  add   rax, r8
//! 18006a520  jmp   rax
//! ```
//!
//! Cases run from -1 to 5, so the table's first entry sits one slot before
//! `0x18006a650`. Bytes: CrashLoggerSSE 1.25.0 (MIT), `CrashLogger.dll`
//! sha256 c5ef5415…8122, function `0x18006a500` and its table. Reported in
//! morluto/rea discussion 3858 (Update 3): the body stopped at the jump.


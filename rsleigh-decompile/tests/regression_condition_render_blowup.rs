fn decompile() -> String {
    let mut decoder = Decoder::new(Architecture::X86_64);
    let mut instructions = Vec::new();
    let mut address = BASE;
    while address < END {
        let inst = decoder
            .decode(&BYTES[(address - BASE) as usize..], address)
            .unwrap();
        let len = inst.len;
        instructions.push((address, inst));
        address += len;
    }
    rsleigh_decompile::decompile(Architecture::X86_64, &instructions)
}

#[test]
fn shared_condition_subterms_print_in_bounded_time_and_size() {
    let (send, receive) = mpsc::channel();
    std::thread::Builder::new()
        .stack_size(64 * 1024 * 1024)
        .spawn(move || send.send(decompile()).unwrap())
        .unwrap();
    // The fixed printer takes well under a second; before, minutes.
    let output = receive
        .recv_timeout(Duration::from_secs(30))
        .expect("decompiling 0x18012e350 did not finish within 30 s");
    let longest = output.lines().map(str::len).max().unwrap_or(0);
    assert!(longest <= 2000, "a {longest}-byte line:\n{output}");
}
